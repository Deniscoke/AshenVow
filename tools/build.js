#!/usr/bin/env node
// Build the playable game into dist/ (what Vercel serves) and, with --zip, release/ashen-vow-itch.zip (itch.io).
//
//   node tools/build.js          dist/ only
//   node tools/build.js --zip    dist/ + release/ashen-vow-itch.zip
//
// No transpiling: the game is plain JS. The build only reshapes it for the web:
//   - every script in src/files.js order is joined into one game.<hash>.js (1 request instead of ~55);
//   - the voice lines are packed into one file per dialogue (itch.io allows at most 1000 files per ZIP, and
//     a phone fetches one pack when a conversation starts instead of one request per line);
//   - file names carry a content hash, so browsers may cache them forever and never play a stale take.
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const zlib = require('zlib');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'dist');
const ZIP = path.join(ROOT, 'release', 'ashen-vow-itch.zip');
const ITCH_MAX_FILES = 1000;
const hash8 = (buf) => crypto.createHash('sha1').update(buf).digest('hex').slice(0, 8);
const write = (rel, data) => { const f = path.join(OUT, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, data); };

fs.rmSync(OUT, { recursive: true, force: true });

// ---- voices: one pack per dialogue, manifest entries become [pack, offset, length]
const voiceSrc = fs.readFileSync(path.join(ROOT, 'assets/voice/manifest.js'), 'utf8');
const sandbox = { window: {} };
vm.runInNewContext(voiceSrc, sandbox);
const voiceMap = sandbox.window.AV_VOICE || {};
const groups = {};
for (const key of Object.keys(voiceMap).sort()) (groups[key.split('|')[0]] = groups[key.split('|')[0]] || []).push(key);
const packed = {};
let packBytes = 0;
for (const [did, keys] of Object.entries(groups)) {
  const parts = [];
  const spans = [];
  let off = 0;
  for (const key of keys) {
    const buf = fs.readFileSync(path.join(ROOT, voiceMap[key]));
    const isMp3 = buf.slice(0, 3).toString('latin1') === 'ID3' || (buf[0] === 0xff && (buf[1] & 0xe0) === 0xe0);
    if (!isMp3) throw new Error(`voice ${key}: ${voiceMap[key]} is not an MP3`);
    parts.push(buf);
    spans.push([key, off, buf.length]);
    off += buf.length;
  }
  const pack = Buffer.concat(parts);
  const rel = `assets/voice/${did.replace(/[^a-z0-9_-]+/gi, '_')}.${hash8(pack)}.bin`;
  write(rel, pack);
  packBytes += pack.length;
  for (const [key, o, len] of spans) packed[key] = [rel, o, len];
}
const voiceManifest = '// Generated by tools/build.js - dialogue page -> [pack, byte offset, byte length].\nwindow.AV_VOICE = ' +
  JSON.stringify(packed) + ';\n';

// ---- scripts: one bundle in load order; a file that throws is reported but does not stop the rest (as before)
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'src/files.js'), 'utf8'), ctx);
const FILES = ctx.window.AV_FILES;
let bundle = '// ASHEN VOW - built by tools/build.js from src/ (see src/files.js for the load order).\n' +
  'window.AV_FILES = ' + JSON.stringify(FILES) + ';\nwindow.AV_LOAD_ERRORS = [];\n';
for (const rel of FILES) {
  const src = rel === 'assets/voice/manifest.js' ? voiceManifest : fs.readFileSync(path.join(ROOT, rel), 'utf8');
  bundle += `\n// ---- ${rel}\ntry {\n${src}\n} catch (e) { window.AV_LOAD_ERRORS.push(${JSON.stringify(rel)}); console.error('[AV] ${rel}', e); }\n`;
}
bundle += '\nif (window.AV && window.AV.boot) window.AV.boot();\n';
const bundleName = `game.${hash8(Buffer.from(bundle))}.js`;
write(bundleName, bundle);

// ---- page, web manifest, icons
const LOADER = '<script src="src/files.js" data-autoload="1"></script>';
const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
if (!html.includes(LOADER)) throw new Error('index.html: loader tag not found, cannot point it at the bundle');
write('index.html', html.replace(LOADER, `<script src="${bundleName}"></script>`));
write('manifest.webmanifest', fs.readFileSync(path.join(ROOT, 'manifest.webmanifest')));
for (const f of fs.readdirSync(path.join(ROOT, 'assets'))) {
  if (/\.(png|ico|svg)$/i.test(f)) write('assets/' + f, fs.readFileSync(path.join(ROOT, 'assets', f)));
}

// ---- summary
const files = [];
(function walk(d) {
  for (const f of fs.readdirSync(d)) { const q = path.join(d, f); if (fs.statSync(q).isDirectory()) walk(q); else files.push(q); }
})(OUT);
const total = files.reduce((n, f) => n + fs.statSync(f).size, 0);
const mb = (n) => (n / 1048576).toFixed(1) + ' MB';
console.log(`dist/ ready: ${files.length} files, ${mb(total)} (bundle ${bundleName} ${mb(bundle.length)}, ` +
  `${Object.keys(groups).length} voice packs ${mb(packBytes)}, ${Object.keys(packed).length} lines)`);

if (process.argv.includes('--zip')) {
  if (files.length > ITCH_MAX_FILES) throw new Error(`itch.io accepts at most ${ITCH_MAX_FILES} files, build has ${files.length}`);
  const entries = files.map((f) => ({ name: path.relative(OUT, f).split(path.sep).join('/'), data: fs.readFileSync(f) }));
  fs.mkdirSync(path.dirname(ZIP), { recursive: true });
  fs.writeFileSync(ZIP, zip(entries));
  console.log(`release/ashen-vow-itch.zip ready: ${entries.length} files, ${mb(fs.statSync(ZIP).size)} (index.html at the root)`);
}

// Minimal ZIP writer (no dependencies). Text is deflated; MP3 packs and PNGs are stored (already compressed).
function zip(entries) {
  const CRC = new Int32Array(256).map((_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c; });
  const crc32 = (buf) => { let c = -1; for (let i = 0; i < buf.length; i++) c = CRC[(c ^ buf[i]) & 0xff] ^ (c >>> 8); return (c ^ -1) >>> 0; };
  const DOS_DATE = ((2026 - 1980) << 9) | (1 << 5) | 1;   // fixed timestamp: identical input -> identical zip
  const local = [];
  const central = [];
  let offset = 0;
  for (const e of entries) {
    const name = Buffer.from(e.name, 'utf8');
    const deflate = /\.(html|js|json|webmanifest|css|svg|txt|md)$/i.test(e.name);
    const body = deflate ? zlib.deflateRawSync(e.data, { level: 9 }) : e.data;
    const crc = crc32(e.data);
    const head = Buffer.alloc(30);
    head.writeUInt32LE(0x04034b50, 0); head.writeUInt16LE(20, 4); head.writeUInt16LE(0x0800, 6);
    head.writeUInt16LE(deflate ? 8 : 0, 8); head.writeUInt16LE(0, 10); head.writeUInt16LE(DOS_DATE, 12);
    head.writeUInt32LE(crc, 14); head.writeUInt32LE(body.length, 18); head.writeUInt32LE(e.data.length, 22);
    head.writeUInt16LE(name.length, 26); head.writeUInt16LE(0, 28);
    local.push(head, name, body);
    const dir = Buffer.alloc(46);
    dir.writeUInt32LE(0x02014b50, 0); dir.writeUInt16LE(20, 4); dir.writeUInt16LE(20, 6); dir.writeUInt16LE(0x0800, 8);
    dir.writeUInt16LE(deflate ? 8 : 0, 10); dir.writeUInt16LE(0, 12); dir.writeUInt16LE(DOS_DATE, 14);
    dir.writeUInt32LE(crc, 16); dir.writeUInt32LE(body.length, 20); dir.writeUInt32LE(e.data.length, 24);
    dir.writeUInt16LE(name.length, 28); dir.writeUInt32LE(offset, 42);
    central.push(dir, name);
    offset += head.length + name.length + body.length;
  }
  const cd = Buffer.concat(central);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(entries.length, 8); end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(offset, 16);
  return Buffer.concat([...local, cd, end]);
}
